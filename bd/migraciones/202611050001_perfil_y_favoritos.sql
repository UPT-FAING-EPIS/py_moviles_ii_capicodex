-- US-17 y US-19: perfil auditable y favoritos asociados a la cuenta autenticada.
begin;

create table if not exists public.actualizaciones_perfil (
  id bigint generated by default as identity primary key,
  usuario_deportista_id integer not null references public.usuarios_deportistas(id) on delete cascade,
  actualizado_en timestamptz not null default now(),
  campos_modificados text[] not null default '{}'
);

alter table public.actualizaciones_perfil enable row level security;

drop policy if exists perfil_actualizaciones_propias on public.actualizaciones_perfil;
create policy perfil_actualizaciones_propias on public.actualizaciones_perfil
  for select to authenticated using (
    usuario_deportista_id in (
      select id from public.usuarios_deportistas where auth_id = (select auth.uid())
    )
  );

create or replace function public.registrar_actualizacion_perfil()
returns trigger language plpgsql security definer set search_path = '' as $$
declare
  modificados text[] := '{}';
begin
  if old.username is distinct from new.username then modificados := array_append(modificados, 'username'); end if;
  if old.nombre is distinct from new.nombre then modificados := array_append(modificados, 'nombre'); end if;
  if old.apellidos is distinct from new.apellidos then modificados := array_append(modificados, 'apellidos'); end if;
  if old.telefono is distinct from new.telefono then modificados := array_append(modificados, 'telefono'); end if;
  if old.fecha_nacimiento is distinct from new.fecha_nacimiento then modificados := array_append(modificados, 'fecha_nacimiento'); end if;
  if old.genero is distinct from new.genero then modificados := array_append(modificados, 'genero'); end if;
  if old.nivel_habilidad is distinct from new.nivel_habilidad then modificados := array_append(modificados, 'nivel_habilidad'); end if;
  if old.imagen_perfil is distinct from new.imagen_perfil then modificados := array_append(modificados, 'imagen_perfil'); end if;
  if cardinality(modificados) > 0 then
    insert into public.actualizaciones_perfil (usuario_deportista_id, campos_modificados)
    values (new.id, modificados);
  end if;
  return new;
end;
$$;

drop trigger if exists auditar_actualizacion_perfil on public.usuarios_deportistas;
create trigger auditar_actualizacion_perfil
  after update on public.usuarios_deportistas
  for each row execute function public.registrar_actualizacion_perfil();

create table if not exists public.instituciones_favoritas (
  usuario_deportista_id integer not null references public.usuarios_deportistas(id) on delete cascade,
  institucion_deportiva_id integer not null references public.instituciones_deportivas(id) on delete cascade,
  creado_en timestamptz not null default now(),
  primary key (usuario_deportista_id, institucion_deportiva_id)
);

alter table public.instituciones_favoritas enable row level security;

drop policy if exists favoritos_propios_select on public.instituciones_favoritas;
create policy favoritos_propios_select on public.instituciones_favoritas
  for select to authenticated using (
    usuario_deportista_id in (select id from public.usuarios_deportistas where auth_id = (select auth.uid()))
  );
drop policy if exists favoritos_propios_insert on public.instituciones_favoritas;
create policy favoritos_propios_insert on public.instituciones_favoritas
  for insert to authenticated with check (
    usuario_deportista_id in (select id from public.usuarios_deportistas where auth_id = (select auth.uid()))
  );
drop policy if exists favoritos_propios_delete on public.instituciones_favoritas;
create policy favoritos_propios_delete on public.instituciones_favoritas
  for delete to authenticated using (
    usuario_deportista_id in (select id from public.usuarios_deportistas where auth_id = (select auth.uid()))
  );

grant select on public.actualizaciones_perfil to authenticated;
grant select, insert, delete on public.instituciones_favoritas to authenticated;

commit;
