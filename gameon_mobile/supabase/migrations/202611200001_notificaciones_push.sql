create table if not exists public.notificaciones (
  id bigint generated by default as identity primary key,
  usuario_id bigint not null references public.usuarios_deportistas(id) on delete cascade,
  titulo text not null,
  mensaje text not null default '',
  tipo text not null default 'general',
  referencia_id bigint,
  fecha timestamptz not null default now(),
  leido boolean not null default false
);

create index if not exists notificaciones_usuario_fecha_idx
  on public.notificaciones (usuario_id, fecha desc);

alter table public.notificaciones enable row level security;

create policy "Usuarios leen sus notificaciones"
  on public.notificaciones for select to authenticated
  using (exists (select 1 from public.usuarios_deportistas u where u.id = notificaciones.usuario_id and u.auth_id = auth.uid()));

create policy "Usuarios crean sus notificaciones"
  on public.notificaciones for insert to authenticated
  with check (exists (select 1 from public.usuarios_deportistas u where u.id = notificaciones.usuario_id and u.auth_id = auth.uid()));

create policy "Usuarios actualizan sus notificaciones"
  on public.notificaciones for update to authenticated
  using (exists (select 1 from public.usuarios_deportistas u where u.id = notificaciones.usuario_id and u.auth_id = auth.uid()))
  with check (exists (select 1 from public.usuarios_deportistas u where u.id = notificaciones.usuario_id and u.auth_id = auth.uid()));

alter table public.notificaciones replica identity full;
alter publication supabase_realtime add table public.notificaciones;
