-- US-26: una calificación editable por cada reserva completada.
begin;

create table if not exists public.calificaciones_instalaciones (
  id bigint generated by default as identity primary key,
  reserva_id integer not null unique references public.reservas(id) on delete cascade,
  institucion_deportiva_id integer not null references public.instituciones_deportivas(id) on delete cascade,
  usuario_id integer not null references public.usuarios_deportistas(id) on delete cascade,
  puntuacion smallint not null check (puntuacion between 1 and 5),
  comentario text,
  creado_en timestamp without time zone not null default current_timestamp,
  actualizado_en timestamp without time zone not null default current_timestamp,
  constraint calificaciones_comentario_longitud check (comentario is null or char_length(comentario) <= 500)
);

alter table public.calificaciones_instalaciones enable row level security;
revoke all on public.calificaciones_instalaciones from anon, authenticated;

-- La app nunca recibe permiso directo de inserción o edición: esta función
-- comprueba la cuenta autenticada, la propiedad y el estado final de la reserva.
create or replace function public.guardar_calificacion_instalacion(
  p_reserva_id integer,
  p_puntuacion smallint,
  p_comentario text default null
) returns table (
  id bigint, reserva_id integer, institucion_deportiva_id integer,
  puntuacion smallint, comentario text, creado_en timestamp without time zone,
  actualizado_en timestamp without time zone
) language plpgsql security definer set search_path = '' as $$
declare
  v_usuario_id integer;
  v_institucion_id integer;
  v_comentario text := nullif(btrim(p_comentario), '');
begin
  if auth.uid() is null then
    raise exception 'Inicia sesión para calificar' using errcode = '42501';
  end if;
  if p_puntuacion not between 1 and 5 then
    raise exception 'La puntuación debe estar entre 1 y 5' using errcode = '22023';
  end if;
  if v_comentario is not null and char_length(v_comentario) > 500 then
    raise exception 'El comentario no puede superar 500 caracteres' using errcode = '22023';
  end if;

  select u.id into v_usuario_id
  from public.usuarios_deportistas u where u.auth_id = auth.uid();
  if v_usuario_id is null then
    raise exception 'Cuenta deportista no autorizada' using errcode = '42501';
  end if;

  select i.id into v_institucion_id
  from public.reservas r
  join public.areas_deportivas a on a.id = r.area_deportiva_id
  join public.instituciones_deportivas i on i.id = a.institucion_deportiva_id
  where r.id = p_reserva_id
    and r.id_usuario = v_usuario_id
    and lower(r.estado) = 'completada';
  if v_institucion_id is null then
    raise exception 'Solo puedes calificar una reserva propia completada' using errcode = '42501';
  end if;

  return query
  insert into public.calificaciones_instalaciones
    (reserva_id, institucion_deportiva_id, usuario_id, puntuacion, comentario)
  values (p_reserva_id, v_institucion_id, v_usuario_id, p_puntuacion, v_comentario)
  on conflict (reserva_id) do update set
    puntuacion = excluded.puntuacion,
    comentario = excluded.comentario,
    actualizado_en = current_timestamp
  returning calificaciones_instalaciones.id, calificaciones_instalaciones.reserva_id,
    calificaciones_instalaciones.institucion_deportiva_id,
    calificaciones_instalaciones.puntuacion, calificaciones_instalaciones.comentario,
    calificaciones_instalaciones.creado_en, calificaciones_instalaciones.actualizado_en;
end;
$$;

create or replace function public.mi_calificacion_reserva(p_reserva_id integer)
returns table (
  id bigint, reserva_id integer, institucion_deportiva_id integer,
  puntuacion smallint, comentario text, creado_en timestamp without time zone,
  actualizado_en timestamp without time zone
) language sql stable security definer set search_path = '' as $$
  select c.id, c.reserva_id, c.institucion_deportiva_id, c.puntuacion,
    c.comentario, c.creado_en, c.actualizado_en
  from public.calificaciones_instalaciones c
  join public.usuarios_deportistas u on u.id = c.usuario_id
  where c.reserva_id = p_reserva_id and u.auth_id = auth.uid();
$$;

create or replace function public.actualizar_promedio_calificacion_instalacion()
returns trigger language plpgsql security definer set search_path = '' as $$
declare v_institucion_id integer;
begin
  if tg_op = 'DELETE' then
    v_institucion_id := old.institucion_deportiva_id;
  else
    v_institucion_id := new.institucion_deportiva_id;
  end if;
  update public.instituciones_deportivas
  set calificacion = coalesce((
    select round(avg(c.puntuacion)::numeric, 2)
    from public.calificaciones_instalaciones c
    where c.institucion_deportiva_id = v_institucion_id
  ), 0)
  where id = v_institucion_id;
  if tg_op = 'DELETE' then return old; end if;
  return new;
end;
$$;

drop trigger if exists actualizar_promedio_calificacion on public.calificaciones_instalaciones;
create trigger actualizar_promedio_calificacion
after insert or update of puntuacion or delete on public.calificaciones_instalaciones
for each row execute function public.actualizar_promedio_calificacion_instalacion();

revoke all on function public.guardar_calificacion_instalacion(integer, smallint, text) from public, anon;
revoke all on function public.mi_calificacion_reserva(integer) from public, anon;
grant execute on function public.guardar_calificacion_instalacion(integer, smallint, text) to authenticated;
grant execute on function public.mi_calificacion_reserva(integer) to authenticated;
commit;
